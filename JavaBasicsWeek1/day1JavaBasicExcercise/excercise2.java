package day1JavaBasicExcercise;

public class excercise2 {

	public static void main(String[] args) {
		// Printing the sum (addition), multiply, subtract, divide and remainder of two numbers.
		
		int num1 = 15 ;
		int num2 = 3 ;
		
		System.out.println("Addition of " + num1 +" and "+num2 +" is "+ (num1 + num2));
		System.out.println("Multiplication of " + num1 +" and "+num2 +" is "+ (num1 * num2));
		System.out.println("Division of " + num1 +" by "+num2 +" is "+ (num1 / num2));
		System.out.println("Remainder of " + num1 +" by "+num2 +" is "+ (num1 % num2));
		
	}

}
